SKIN = 0.5        # 与 gateway/tools.py 的 SKIN_MM 一致


def make_extra_tasks():
    return tasks_from(EXTRA)


def check():
    """几何自检：轮廓在毛坯内、不切穿、孔在毛坯内。

    另加一条"文案—答案一致性"检查：文案里写成 `(x,y) 这个位置不钻/取消` 的坐标，
    必须真的不在答案里。E12 第一版就是漏了这条，15/15 个模型被误判成 0.50。
    """
    bad = []
    for t in make_extra_tasks():
        L, W, H = t["size"]
        for c in t["calls"]:
            a = c["args"]
            if c["tool"] == "cad.pocket":
                x0, x1 = a["center_x"] - a["width"] / 2, a["center_x"] + a["width"] / 2
                y0, y1 = a["center_y"] - a["height"] / 2, a["center_y"] + a["height"] / 2
                if x0 < 0 or y0 < 0 or x1 > L or y1 > W:
                    bad.append((t["id"], "轮廓越界", c))
                if a["depth"] > H - SKIN:
                    bad.append((t["id"], "切穿", c))
            elif c["tool"] == "cad.hole":
                if not (0 < a["x"] < L and 0 < a["y"] < W):
                    bad.append((t["id"], "孔越界", c))
                if a.get("depth", 0) > H - SKIN:
                    bad.append((t["id"], "孔切穿", c))
    _check_skip_consistency(bad)
    return bad


def _check_skip_consistency(bad):
    import re
    for t in make_extra_tasks():
        skip = {(float(m.group(1)), float(m.group(2)))
                for m in re.finditer(r"\((\d+(?:\.\d+)?),\s*(\d+(?:\.\d+)?)\)\s*这个位置",
                                     t["text"])}
        for c in t["calls"]:
            a = c["args"]
            if c["tool"] == "cad.hole" and (a["x"], a["y"]) in skip:
                bad.append((t["id"], "文案说不做但答案里有", c))
            if c["tool"] == "cad.pocket":
                for sx, sy in skip:
                    if (abs(a["center_x"] - sx) <= a["width"] / 2
                            and abs(a["center_y"] - sy) <= a["height"] / 2):
                        bad.append((t["id"], "文案说不做但答案覆盖该点", c))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--print", action="store_true", dest="show")
    args = ap.parse_args()
    tasks = make_extra_tasks()
    if args.show:
        for t in tasks:
            print("\n[%s] %s  （%d 个特征）" % (t["id"], t["tag"], len(t["calls"]) - 1))
            print("  ", t["text"])
            for c in t["calls"][1:]:
                print("     →", c["tool"], c["args"])
    bad = check()
    print("\n%d 条工单｜几何自检：%s" % (len(tasks), "全部合法" if not bad else bad))
    from collections import Counter
    print("标签分布：", dict(Counter(t["tag"] for t in tasks)))
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
